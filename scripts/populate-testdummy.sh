#!/usr/bin/env bash
# Rebuilds a GitHub repo (default cvanfleteren/testdummy) from nothing into a fixture for trying jazygit by hand.
# Destructive: closes every open PR, deletes every remote branch except main, and force-pushes main.
#
# Usage: scripts/populate-testdummy.sh [owner/repo]
#
# Result:
#   main          yaml, sql, json and ts files; big.txt with 20000 lines, a commit indenting every line of it,
#                 a commit appending one line; a merge train of nested merges 5 levels deep
#   catch-up      a branch that merged main in twice to catch up while main moved on
#   feat/a..e     a stack of 5 branches, each with an open PR based on the previous one (feat/a on main)
#   🚀-launch/✨-sparkles-🎉   a branch with emojis in its name
set -euo pipefail

REPO="${1:-cvanfleteren/testdummy}"
URL="git@github.com:${REPO}.git"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Fixed, increasing timestamps so the history reads as a timeline and reruns look alike.
TICK=0
commit() {
  TICK=$((TICK + 1))
  local when="@$((1767225600 + TICK * 3600)) +0000"
  GIT_AUTHOR_DATE="$when" GIT_COMMITTER_DATE="$when" git -c commit.gpgsign=false commit -q "$@"
}
merge() {
  TICK=$((TICK + 1))
  local when="@$((1767225600 + TICK * 3600)) +0000"
  GIT_AUTHOR_DATE="$when" GIT_COMMITTER_DATE="$when" git -c commit.gpgsign=false merge -q --no-ff "$@"
}

echo "== Cleaning ${REPO}"
for pr in $(gh pr list -R "$REPO" --state open --limit 200 --json number -q '.[].number'); do
  gh pr close -R "$REPO" "$pr" >/dev/null
  echo "closed PR #${pr}"
done
for branch in $(git ls-remote --heads "$URL" | sed 's|.*refs/heads/||'); do
  if [[ "$branch" != main ]]; then
    git push -q "$URL" --delete "$branch"
    echo "deleted branch ${branch}"
  fi
done

cd "$WORK"
git init -q -b main
git remote add origin "$URL"

echo "== Building main"
cat > README.md <<'EOF'
# testdummy

Fixture repository for jazygit. Regenerated by `scripts/populate-testdummy.sh` in the jazygit repo; anything here gets
wiped on the next run.
EOF
git add README.md
commit -m "Initial commit"

cat > config.yaml <<'EOF'
app:
  name: testdummy
  port: 8080
  features:
    - search
    - export
database:
  url: postgres://localhost:5432/testdummy
  pool:
    min: 2
    max: 10
logging:
  level: info
  format: json
EOF
git add config.yaml
commit -m "Add application config"

cat > schema.sql <<'EOF'
CREATE TABLE customers (
    id          BIGSERIAL PRIMARY KEY,
    email       TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE orders (
    id           BIGSERIAL PRIMARY KEY,
    customer_id  BIGINT NOT NULL REFERENCES customers (id),
    total_cents  INTEGER NOT NULL CHECK (total_cents >= 0),
    status       TEXT NOT NULL DEFAULT 'pending',
    placed_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX orders_customer_idx ON orders (customer_id);

SELECT c.name, count(o.id) AS order_count, sum(o.total_cents) / 100.0 AS total
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.id
GROUP BY c.name
ORDER BY total DESC NULLS LAST;
EOF
git add schema.sql
commit -m "Add database schema"

cat > data.json <<'EOF'
{
  "customers": [
    { "id": 1, "email": "ada@example.com", "name": "Ada", "tags": ["vip", "early"] },
    { "id": 2, "email": "grace@example.com", "name": "Grace", "tags": [] },
    { "id": 3, "email": "linus@example.com", "name": "Linus", "tags": ["beta"] }
  ],
  "orders": [
    { "id": 10, "customerId": 1, "totalCents": 4999, "status": "shipped" },
    { "id": 11, "customerId": 3, "totalCents": 1250, "status": "pending" }
  ],
  "meta": { "version": 1, "generated": true, "nothing": null }
}
EOF
git add data.json
commit -m "Add sample data"

mkdir -p src
cat > src/app.ts <<'EOF'
interface Customer {
  readonly id: number;
  readonly email: string;
  readonly name: string;
  readonly tags: readonly string[];
}

type OrderStatus = "pending" | "shipped" | "cancelled";

interface Order {
  readonly id: number;
  readonly customerId: number;
  readonly totalCents: number;
  readonly status: OrderStatus;
}

export function totalFor(customer: Customer, orders: readonly Order[]): number {
  return orders
    .filter((order) => order.customerId === customer.id && order.status !== "cancelled")
    .reduce((sum, order) => sum + order.totalCents, 0);
}

export const greet = (customer: Customer): string => `Hello, ${customer.name}!`;
EOF
git add src/app.ts
commit -m "Add TypeScript app"

echo "== Big file"
seq 1 20000 | awk '{ printf "line %05d: the quick brown fox jumps over the lazy dog\n", $1 }' > big.txt
git add big.txt
commit -m "Add big.txt with 20000 lines"

sed -i 's/^/ /' big.txt
git add big.txt
commit -m "Indent every line of big.txt by one space"

echo " line 20001: the very last line" >> big.txt
git add big.txt
commit -m "Append a line to the end of big.txt"

echo "== Merge train"
# train/1 branches off main, train/2 off train/1, ... train/5 off train/4. Every level then gets its own commit after
# its child branched off, so each merge below joins two diverged lines: 5 levels of merges nested inside each other.
mkdir -p train
for level in 1 2 3 4 5; do
  git switch -q -c "train/${level}"
  echo "level ${level} started" > "train/level-${level}.txt"
  git add "train/level-${level}.txt"
  commit -m "Train ${level}: start"
done
for level in 5 4 3 2; do
  parent=$((level - 1))
  git switch -q "train/${parent}"
  echo "level ${parent} kept going while level ${level} was in flight" >> "train/level-${parent}.txt"
  git add "train/level-${parent}.txt"
  commit -m "Train ${parent}: work while train ${level} is open"
  merge "train/${level}" -m "Merge train/${level} into train/${parent}"
done
git switch -q main
echo "- see train/ for the merge train" >> README.md
git add README.md
commit -m "Mention the merge train in the README"
merge train/1 -m "Merge train/1 into main"
git branch -q -D train/1 train/2 train/3 train/4 train/5

echo "== Catch-up branch"
# catch-up branches off main and merges main in twice to catch up while main moves on, so its divergence from main
# has merges whose other parent is on main, outside the commits only on the branch.
git switch -q -c catch-up
mkdir -p catch-up
for round in 1 2; do
  git switch -q main
  echo "- main moved on (${round})" >> README.md
  git add README.md
  commit -m "Main moves on while catch-up is open (${round})"
  git switch -q catch-up
  echo "round ${round}" >> catch-up/notes.txt
  git add catch-up/notes.txt
  commit -m "Catch-up: work before catching up (${round})"
  merge main -m "Merge main into catch-up (${round})"
done
echo "done" >> catch-up/notes.txt
git add catch-up/notes.txt
commit -m "Catch-up: work after catching up"
git switch -q main

echo "== Stack feat/a..feat/e"
base=main
for name in a b c d e; do
  git switch -q -c "feat/${name}" "$base"
  cat > "src/feature-${name}.ts" <<EOF
export function feature${name^^}(input: string): string {
  return \`feature ${name}: \${input}\`;
}
EOF
  git add "src/feature-${name}.ts"
  commit -m "feat/${name}: add feature ${name}"
  cat >> src/app.ts <<EOF

export { feature${name^^} } from "./feature-${name}";
EOF
  git add src/app.ts
  commit -m "feat/${name}: export feature ${name} from app"
  base="feat/${name}"
done

echo "== Emoji branch"
EMOJI_BRANCH="🚀-launch/✨-sparkles-🎉"
git switch -q -c "$EMOJI_BRANCH" main
echo "🚀 ✨ 🎉 launch notes" > LAUNCH.md
git add LAUNCH.md
commit -m "Add launch notes 🚀"
git switch -q main

echo "== Pushing"
git push -q --force origin main
git push -q --force origin catch-up feat/a feat/b feat/c feat/d feat/e "$EMOJI_BRANCH"

echo "== Opening stacked PRs"
base=main
for name in a b c d e; do
  gh pr create -R "$REPO" --base "$base" --head "feat/${name}" \
    --title "Feature ${name^^}" \
    --body "Part of the feat/a..feat/e stack; based on \`${base}\`."
  base="feat/${name}"
done

echo "== Done: https://github.com/${REPO}"
